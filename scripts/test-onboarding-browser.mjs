import {chromium} from 'playwright';
const url=process.env.KOINE_TEST_URL||'http://127.0.0.1:4173/';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto(url,{waitUntil:'networkidle'});
if(await page.locator('#guidance-dialog').count())throw new Error('Onboarding dialog opened without user action.');
await page.locator('#guided-plan [data-guide-task="0"]').click();
const dialog=page.locator('#guidance-dialog');await dialog.waitFor({state:'visible'});
await dialog.getByRole('button',{name:'Set up my path'}).click();
await page.selectOption('#guide-experience','coursework');
await page.selectOption('#guide-goal','read-nt');
await page.locator('input[name="guide-minutes"][value="25"]').check();
await page.selectOption('#guide-days','5');
await dialog.getByRole('button',{name:'Continue'}).click();
const learningBefore=await page.evaluate(()=>localStorage.getItem('koine-path-learning-v3'));
await dialog.getByRole('button',{name:'Start diagnostic'}).click();
for(let i=0;i<16;i++){
  const correct=await page.evaluate(()=>{const s=window.KOINE_GUIDANCE_ENGINE.snapshot(),q=window.KoineGuidance.QUESTIONS.find(x=>s.placement.answers[x.id]===undefined);return q.correct});
  await dialog.locator('[data-guide-answer]').nth(correct).click();
}
await dialog.getByText(/Provisional level: S7/).waitFor();
const learningAfter=await page.evaluate(()=>localStorage.getItem('koine-path-learning-v3'));
if(learningBefore!==learningAfter)throw new Error('Placement mutated canonical learning state.');
await dialog.getByRole('button',{name:'Use this study path'}).click();
await page.locator('#guided-plan').getByText('Accelerated validation path').waitFor();
const plan=await page.evaluate(()=>window.KOINE_GUIDANCE_ENGINE.getGuidedPlan());
if(plan.tasks.reduce((s,t)=>s+t.minutes,0)!==25)throw new Error('25-minute guided plan budget drifted.');
await page.getByRole('button',{name:'Progress'}).click();
await page.locator('#study-path-settings').getByText(/S7 · Reading Fluency & Exegetical Competence/).waitFor();
await page.reload({waitUntil:'networkidle'});
if(await page.locator('#guidance-dialog').count())throw new Error('Completed onboarding reopened after reload.');
const persisted=await page.evaluate(()=>JSON.parse(localStorage.getItem('koine-path-guidance-v1')));
if(persisted?.onboarding?.status!=='complete'||persisted?.placement?.stageId!=='S7')throw new Error('Guided study state did not persist.');
const todayActive=await page.locator('#today').evaluate(el=>el.classList.contains('active'));
if(!todayActive)throw new Error('Fresh reload did not return to the default Today view.');
await page.setViewportSize({width:390,height:844});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
if(overflow>1)throw new Error(`V1.3 introduced horizontal overflow: ${overflow}px`);
if(errors.length)throw new Error(`Browser errors: ${errors.join(' | ')}`);
await browser.close();
console.log('V1.3 onboarding browser flow, mastery firewall, persistence, and mobile reflow: PASS');
