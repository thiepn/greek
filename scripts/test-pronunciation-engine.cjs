const assert=require('node:assert/strict');
const {MemoryStorage,transcribeWord,transcribe,PronunciationEngine}=require('../pronunciation-engine.js');
const data={defaultProfile:'koine-reconstructed',profiles:{'koine-reconstructed':{id:'koine-reconstructed',tts:false},erasmian:{id:'erasmian',tts:false},modern:{id:'modern',tts:true,locale:'el-GR'}},drills:[{id:'k',profile:'koine-reconstructed',answer:0}]};
assert.equal(transcribeWord('λόγος','koine-reconstructed'),'lˈoɣos');
assert.equal(transcribeWord('λόγος','erasmian'),'lˈogos');
assert.equal(transcribeWord('θεός','modern'),'θeˈos');
assert.equal(transcribeWord('ἁ','koine-reconstructed'),'ha');
assert.equal(transcribeWord('ει','koine-reconstructed'),'i');
assert.equal(transcribeWord('η','koine-reconstructed'),'e');
assert.equal(transcribeWord('η','modern'),'i');
assert.equal(transcribeWord('ω','erasmian'),'oː');
assert.equal(transcribe('Ἐν ἀρχῇ','koine-reconstructed'),'ɛn arxˈe');
const storage=new MemoryStorage(),engine=new PronunciationEngine({data,storage,clock:()=>new Date('2026-08-21T12:00:00Z')});
assert.equal(engine.profile().id,'koine-reconstructed');
assert.equal(engine.speak('λόγος').ok,false,'historical profile must refuse browser TTS');
assert.match(engine.speak('λόγος').reason,/Modern Greek TTS is not substituted/);
assert.equal(engine.answerDrill('k',0),true);assert.equal(engine.stats().drillAccuracy,100);
engine.setRate(9);assert.equal(engine.state.settings.rate,1.35);engine.setRate(.1);assert.equal(engine.state.settings.rate,.55);
engine.setProfile('erasmian');const restored=new PronunciationEngine({data,storage});assert.equal(restored.profile().id,'erasmian');
assert.equal(restored.stats().drillAttempts,1);
console.log('BG12 pronunciation engine tests passed.');